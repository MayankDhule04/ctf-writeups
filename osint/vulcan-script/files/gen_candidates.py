import re

full = "THOSE WHO DO NOT FOLLOW THE PRINCIPLES OF VULCAN LOGIC WILL FAIL. VTOSH KA'TUR NI'VAR, DO NOT PITY THOSE WHO DO NOT FOLLOW LOGIC. HELP THEM SEE REASON. TURN THE VULCAN INTO ENGLISH AND WRAP IT WITH UNDERSCORES TO SEE REASON."
print(full)
print()

def mk(s):
    s = re.sub(r"[^A-Za-z ]", '', s).strip()
    s = re.sub(r'\s+', '_', s).lower()
    return 'spooky{' + s + '}'

candidates = [
  full,
  'THOSE WHO DO NOT FOLLOW THE PRINCIPLES OF VULCAN LOGIC WILL FAIL',
  "VTOSH KA'TUR NI'VAR DO NOT PITY THOSE WHO DO NOT FOLLOW LOGIC HELP THEM SEE REASON",
  'HELP THEM SEE REASON',
  'TURN THE VULCAN INTO ENGLISH AND WRAP IT WITH UNDERSCORES TO SEE REASON',
  'SEE REASON',
  'DO NOT PITY THOSE WHO DO NOT FOLLOW LOGIC',
  'THOSE WHO DO NOT FOLLOW THE PRINCIPLES OF VULCAN LOGIC WILL FAIL TO SEE REASON',
]
for c in candidates:
    print(mk(c))
